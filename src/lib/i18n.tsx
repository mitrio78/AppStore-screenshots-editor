const LOCALE_SHORT_LABELS: Record<AppLocale, string> = {
  en: "EN",
  ru: "RU",
  ja: "日本語",
};

function isAppLocale(value: string | null | undefined): value is AppLocale {
  return APP_LOCALES.includes(value as AppLocale);
}

function normalizeLocale(value: string | null | undefined): AppLocale | null {
  if (!value) return null;
  const base = value.toLowerCase().split("-")[0];
  return isAppLocale(base) ? base : null;
}

function initialAppLocale(): AppLocale {
  if (typeof window === "undefined") return "en";
  try {
    const saved = normalizeLocale(window.localStorage.getItem(APP_LANGUAGE_KEY));
    if (saved) return saved;
  } catch {
    /* ignore */
  }

  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }
  return "en";
}

