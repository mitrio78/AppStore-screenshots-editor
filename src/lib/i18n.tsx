const MESSAGES: Record<AppLocale, Messages> = { en, ru, ja };

type I18nContextValue = {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  messages: Messages;
  localeLabels: typeof LOCALE_LABELS;
  localeShortLabels: typeof LOCALE_SHORT_LABELS;
  deviceLabel: (device: Device) => string;
  layoutLabel: (layout: SlideLayout) => string;
  layoutHint: (layout: SlideLayout) => string;
  themeName: (theme: ThemeId) => string;
  frameColorLabel: (id: string, fallback: string) => string;
};

const I18nContext = React.createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = React.useState<AppLocale>("en");
  const [hydrated, setHydrated] = React.useState(false);

  React.useEffect(() => {
    setLocaleState(initialAppLocale());
    setHydrated(true);
  }, []);

  React.useEffect(() => {
    if (!hydrated) return;
    document.documentElement.lang = locale;
    try {
      window.localStorage.setItem(APP_LANGUAGE_KEY, locale);
    } catch {
      /* ignore */
    }
  }, [hydrated, locale]);

  const value = React.useMemo<I18nContextValue>(() => {
    const messages = MESSAGES[locale];
    return {
      locale,
      setLocale: setLocaleState,
      messages,
      localeLabels: LOCALE_LABELS,
      localeShortLabels: LOCALE_SHORT_LABELS,
      deviceLabel: (device) => messages.devices[device],
      layoutLabel: (layout) => messages.layouts.labels[layout],
      layoutHint: (layout) => messages.layouts.hints[layout],
      themeName: (theme) => messages.themes[theme],
      frameColorLabel: (id, fallback) =>
        (messages.frameColors as Record<string, string>)[id] || fallback,
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = React.useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}

export function supportedAppLocales(): readonly AppLocale[] {
  return APP_LOCALES;
}
