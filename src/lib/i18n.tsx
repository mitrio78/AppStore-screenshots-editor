function isAppLocale(value: string | null | undefined): value is AppLocale {
  return APP_LOCALES.includes(value as AppLocale);
}

// Map a browser/stored locale tag to a supported one. Handles case and region
// tags: an exact (case-insensitive) match wins first (e.g. "zh-cn" -> "zh-CN"),
// then a base-language match (e.g. "de-AT" -> "de", "zh-Hans" -> "zh-CN").
function normalizeLocale(value: string | null | undefined): AppLocale | null {
  if (!value) return null;
  const lower = value.toLowerCase();
  const exact = APP_LOCALES.find((l) => l.toLowerCase() === lower);
  if (exact) return exact;
  const base = lower.split("-")[0];
  const baseMatch = APP_LOCALES.find((l) => l.toLowerCase().split("-")[0] === base);
  return baseMatch ?? null;
}

function initialAppLocale(): AppLocale {
  if (typeof window === "undefined") return "en";
  try {
    const saved = normalizeLocale(window.localStorage.getItem(APP_LANGUAGE_KEY));
    if (saved) return saved;
  } catch {
    /* ignore */
  }

  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }
  return "en";
}

